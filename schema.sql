-- BY DEFAULT (not ALWAYS): PUT /tasks?id=eq.N sends an explicit id,
-- and an ALWAYS identity column rejects explicit values.
create table if not exists public.tasks (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  completed   boolean not null default false
);

alter table public.tasks enable row level security;

-- The publishable key works as the "anon" role. Demo data only, so anyone
-- may read and write. PUT is an upsert and needs both insert and update.
drop policy if exists "tasks_public_select" on public.tasks;
drop policy if exists "tasks_public_insert" on public.tasks;
drop policy if exists "tasks_public_update" on public.tasks;
drop policy if exists "tasks_public_delete" on public.tasks;

create policy "tasks_public_select" on public.tasks
  for select to anon using (true);
create policy "tasks_public_insert" on public.tasks
  for insert to anon with check (true);
create policy "tasks_public_update" on public.tasks
  for update to anon using (true) with check (true);
create policy "tasks_public_delete" on public.tasks
  for delete to anon using (true);

grant select, insert, update, delete on table public.tasks to anon;

-- Test data, inserted only into an empty table.
insert into public.tasks (title, description, completed)
select title, description, completed
from (values
  ('Learn Git', 'Practice Git commands', false),
  ('Create the Supabase table', 'tasks table with RLS policies', true),
  ('Deploy to GitHub Pages', 'Publish the root of the main branch', false)
) as seed (title, description, completed)
where not exists (select 1 from public.tasks);
